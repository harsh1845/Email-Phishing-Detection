/**
 * Official brand / mailer domains that should skip scoring.
 * URL shorteners that hide the destination are NOT treated as trusted
 * unless they belong to a first-party brand (youtu.be, aka.ms, …).
 */
export function buildDefaultAllowlist(): Set<string> {
  const set = new Set<string>();
  for (const d of DEFAULT_ALLOWLIST) {
    const host = d.toLowerCase().replace(/^www\./, '');
    set.add(host);
  }
  return set;
}

export { SHORTENER_KEEP };
